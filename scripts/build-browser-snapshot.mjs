// Bundle the built-in browser's page-side snapshot script.
//
// Input: third_party/playwright-injected/entry.ts (ours) plus the vendored
// Playwright sources it imports. Output: one self-contained IIFE the surface
// evaluates in a bot's tab over CDP (electron/browser-surface.cjs reads it
// at startup). The output is committed so dev and packaged builds carry the
// same bytes; re-run this after touching anything under
// third_party/playwright-injected.
import { build } from "esbuild";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const vendored = join(root, "third_party", "playwright-injected");
const outfile = join(root, "apps", "shell", "resources", "browser-snapshot.js");
const upstream = readFileSync(join(vendored, "UPSTREAM_COMMIT"), "utf8").trim();

await build({
  entryPoints: [join(vendored, "entry.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["chrome120"],
  minify: true,
  legalComments: "none",
  outfile,
  banner: {
    js:
      `/* OpenFolks built-in browser snapshot. Bundled from Microsoft Playwright (Apache-2.0, ` +
      `upstream ${upstream.slice(0, 12)}); sources and license in third_party/playwright-injected. ` +
      `Generated by scripts/build-browser-snapshot.mjs — do not edit. */`,
  },
  plugins: [
    {
      name: "playwright-isomorphic-alias",
      setup(api) {
        // Playwright's sources import shared modules as `@isomorphic/<name>`.
        api.onResolve({ filter: /^@isomorphic\// }, (args) => ({
          path: join(vendored, "isomorphic", `${args.path.slice("@isomorphic/".length)}.ts`),
        }));
      },
    },
  ],
});
console.log(`wrote ${outfile}`);
